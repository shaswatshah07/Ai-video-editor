export type ClipKind = 'SOURCE_CLIP' | 'MEME_CLIP';

export type ClipStatus = 'ACTIVE' | 'SUGGESTED_SILENCE_CUT' | 'SUGGESTED_MEME' | 'DELETED';

export type TransitionType = 'none' | 'fade' | 'dissolve' | 'wipeleft' | 'wiperight' | 'slideup';

export interface TransitionOut {
  type: TransitionType;
  durationMs: number;
}

export interface TimelineItem {
  id: string;
  kind: ClipKind;
  title: string;
  blobUrl: string;
  sourceStartMs: number;
  sourceEndMs: number;
  durationMs: number;
  projectStartMs: number;
  projectEndMs: number;
  status: ClipStatus;
  transitionOut: TransitionOut;
  meta?: {
    silenceRms?: number;
    silenceSelected?: boolean;
    memeCategory?: string;
    isCustomUpload?: boolean;
    isAddedClip?: boolean;
  };
}

export interface TranscriptWord {
  id: string;
  word: string;
  sourceStartMs: number;
  sourceEndMs: number;
  confidence: number;
  approximate?: boolean;
  edited?: boolean;
  clipId?: string;
}

export type TranscriptModelQuality = 'accurate' | 'fast';
export type TranscriptMode = 'transcribe_hinglish' | 'translate_en' | 'transcribe_en';

export interface TranscriptionMeta {
  modelName: string;
  modelQuality: TranscriptModelQuality;
  mode: TranscriptMode;
  device: 'WebGPU' | 'WASM';
  durationMs: number;
  arabicScriptPercent?: number;
  hasUrduWarning?: boolean;
  lowQualityWarning?: string | null;
  suppressWordRender?: boolean;
}

export interface ChapterMarker {
  id: string;
  title: string;
  sourceMs: number;
  description?: string;
  isAutoGenerated?: boolean;
}

export interface AudioSettings {
  voiceEnhanceEnabled: boolean;  // Speaker Voice Enhancement (80Hz HPF + 250Hz cut + 3kHz boost + compressor)
  noiseRemovalEnabled: boolean;  // Background Noise Removal (100Hz HPF + 7500Hz LPF + noise gate)
  noiseReductionEnabled?: boolean; // backwards compatibility alias
  highPassFreq?: number;
  eqPeakFreq?: number;
  eqGainDb?: number;
  compressorThresholdDb?: number;
}

export interface ProjectEDL {
  id: string;
  title: string;
  sourceDurationMs: number;
  sourceVideoUrl: string;
  sourceFileName: string;
  sourceFileSize: number;
  totalProjectDurationMs: number;
  items: TimelineItem[];
  transcript: TranscriptWord[];
  chapters: ChapterMarker[];
  isDemoSample?: boolean;
  transcriptLanguage?: 'english' | 'hindi';
  transcriptMode?: TranscriptMode;
  transcriptionMeta?: TranscriptionMeta;
  audioSettings: AudioSettings;
  createdAt: number;
  updatedAt: number;
}
